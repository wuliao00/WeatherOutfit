#!/usr/bin/env python3
"""生成 Task 7 Step 5 的人工抽样审定表。

抽样规则刻意写成可复现的固定式（每月 3/9/15/21/27 日，二月也有效），
不靠随机数，这样另一个人重跑能得到同一张表、比对得上。
"""
import json
import pathlib

DS = pathlib.Path("shared/src/commonMain/composeResources/files/today_in_history.json")
OUT = pathlib.Path("docs/content/today-history-review.md")
SAMPLE_DAYS = [3, 9, 15, 21, 27]
TYPE = {1: "事件", 2: "出生", 3: "逝世"}

rows = json.loads(DS.read_text(encoding="utf-8"))
by_day = {}
for r in rows:
    by_day.setdefault((r["m"], r["d"]), []).append(r)

lines = []
w = lines.append
w("# 「历史上的今天」人工抽样审定表（Task 7 Step 5）")
w("")
w("审定人：________　审定日期：2026-____-____　／____-____")
w("")
w("## 为什么要这张表")
w("")
w("结构校验（`tools/validate_today_dataset.py`）只能判形状：条数、句长、句号数、引用残留、未来年份。")
w("它判不了「这句话是不是真的」。撰写规范里「只写能被独立查证的事实」「不写仍在争议中的表述」")
w("两条都标着「人工」，就是因为没有可执行判据。spec 10.6 定的这一步就是把这个缺口交给人。")
w("")
w("全库 1098 条。本轮已做过一轮**逐条对源**：凡是本地日期编目印不到的 178 条")
w("（105 条编目该年该日无记录 + 73 条超出编目 2020 年上限）都查到过外部来源，")
w("改了 20 句（见第三节）。剩下 920 条只做到「该年该日编目里有事」，**没有**逐条核对过是不是同一件事。")
w("")
w("所以这张表要审的是表述层：措辞是否中性、有没有把有争议的说法写成定论、")
w("身份/头衔是否多余、年份与「这句话主张的事」是否对得上。")
w("")
w("## 怎么标")
w("")
w("- 认可：留空即可")
w("- 有疑问：在该行末尾写 `? 一句话说明`")
w("- 确定错：写 `X 应改成什么（或：删）`")
w("- 整月抽完请填第二节的月度小结，尤其「这个月有没有系统性问题」")
w("")
w("## 一、抽样 60 天 × 3 条 = 180 句")
w("")
w("抽样日固定为每月 3、9、15、21、27 日（可复现；2 月取到 27 日仍有效）。")
w("")
for m in range(1, 13):
    w(f"### {m} 月")
    w("")
    w("| 日期 | 年 | 类 | 句子 | 审定 |")
    w("|---|---|---|---|---|")
    for d in SAMPLE_DAYS:
        day = by_day[(m, d)]
        for i, r in enumerate(day):
            date = f"{m}/{d}" if i == 0 else ""
            w(f"| {date} | {r['y']} | {TYPE[r['t']]} | {r['s']} |  |")
    w("")

w("## 二、月度小结")
w("")
w("| 月 | 抽了几句 | 疑问 ? | 错误 X | 系统性问题（若有） |")
w("|---|---|---|---|---|")
for m in range(1, 13):
    w(f"| {m} | 15 |  |  |  |")
w("")

w("## 三、本轮对源核验改过的 20 句（不在抽样里也请过一眼）")
w("")
w("这些是核查轮判定的改动，风险集中在「换上去的新句子本身对不对」，请重点看：")
w("")
w("| 日期 | 年 | 类 | 现句 | 审定 |")
w("|---|---|---|---|---|")
CHANGED = [
    (1, 11, 1935), (3, 10, 2000), (3, 22, 1895),
    (5, 31, 1859), (5, 31, 1889), (6, 22, 2023), (7, 20, 2021),
    (8, 4, 1944), (8, 23, 2023),
    (9, 5, 2016), (9, 12, 2024), (9, 24, 1789),
    (10, 4, 1959), (10, 27, 2024), (11, 24, 2023),
    (12, 4, 1977), (12, 5, 1901), (12, 15, 1890), (12, 22, 1894), (12, 27, 1831),
]
for (m, d, y) in CHANGED:
    hit = [r for r in by_day[(m, d)] if r["y"] == y]
    if not hit:
        w(f"| {m}/{d} | {y} | ? | **（表生成时未找到该条，请人工核对分片）** |  |")
        continue
    r = hit[0]
    w(f"| {m}/{d} | {r['y']} | {TYPE[r['t']]} | {r['s']} |  |")
w("")
w("其中 6 句是整句替换（原句的日期/年份对不上来源）：`12-22`、`12-27`、`12-04`、`09-05`")
w("原来分别写的是华盛顿辞职（实在 12-23）、塔利班入喀布尔（实在 9-27）、开罗会谈（实在 11-22~26）、")
w("月船三号进入月夜休眠（实在 9-02/04）；`12-05` 迪士尼生年由 1915 订正为 1901；")
w("`06-22` 泰坦号一条把 `t` 从 3（逝世）改为 1（事件），因为句子主张的是「残骸被发现、内爆确认」。")
w("")

w("## 四、审定结论")
w("")
w("- [ ] 180 句抽完，疑问与错误已在第三节之外另行列清单")
w("- [ ] 改过的 20 句逐条过目")
w("- [ ] 判定：通过 / 通过后局部修改 / 不通过需重写")
w("- [ ] 若判定不通过：涉及月份 ______，处理方式 ______")
w("")
w("审定签字：________　日期：________")
w("")

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("written", OUT, len(lines), "lines")
